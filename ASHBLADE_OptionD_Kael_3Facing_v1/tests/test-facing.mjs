import assert from 'node:assert/strict';
import { facingFromAngle, selectKaelFacing } from '../src/kael-facing.mjs';
const eq=(a,b)=>assert.equal(a,b);
eq(facingFromAngle(0),'right');
eq(facingFromAngle(Math.PI),'left');
eq(facingFromAngle(Math.PI/2),'center');
eq(facingFromAngle(-Math.PI/2),'center');
eq(facingFromAngle(0.9, 'right'),'right'); // sticky diagonal
const p={state:'move',vx:100,vy:0,aim:0};
eq(selectKaelFacing(p,true,1).facing,'right');
p.vx=0;p.vy=-100;
eq(selectKaelFacing(p,true,1.1).facing,'center');
p.vx=-100;p.vy=0;
eq(selectKaelFacing(p,true,1.2).facing,'left');
p.state='attack';p.atkAng=Math.PI/2;
eq(selectKaelFacing(p,false,1.3).facing,'center');
p.state='skill';p.aim=Math.PI;
eq(selectKaelFacing(p,false,1.4).facing,'left');
p.state='move';
eq(selectKaelFacing(p,false,1.42).facing,'left');
eq(selectKaelFacing(p,false,1.7).facing,'center');
console.log('[PASS] Option D directional logic: center/right/mirrored-left, 360 degree aim independent');
